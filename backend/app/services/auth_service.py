def update_user_role(
    db: Session,
    user_id: UUID,
    role: UserRole,
):
    statement = select(User).where(User.id == user_id)
    result = db.execute(statement)
    user = result.scalar_one_or_none()

    if not user:
        return None

    user.role = role.value

    try:
        db.commit()
    except SQLAlchemyError:
        db.rollback()
        raise
    db.refresh(user)
    return user